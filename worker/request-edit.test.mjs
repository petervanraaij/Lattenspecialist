import assert from 'node:assert/strict';
import {maintenanceFixture} from './maintenance-fixture.mjs';
const f=await maintenanceFixture();
try {
 const reference=f.materials[0].reference;
 const path='/api/admin/reservations/'+reference;
 const labels='/api/admin/operations/materials';
 const load=async()=> (await f.call('/api/admin/reservations')).data.records.find(r=>r.reference===reference);
 const old=await load();
 const selection=JSON.parse(old.maintenanceSelection);
 selection.p.platinum.b++;
 const changed=await f.call(path,'PATCH',{revision:old.revision,maintenanceSelection:JSON.stringify(selection),material:old.material,package:old.package,amount:'3',pickupDate:'2026-12-02',address:'Fictieve straat 1',serviceCode:'LS-TEST23'});
 assert.equal(changed.status,200,JSON.stringify(changed));
 assert.equal(changed.data.record.amount,'3');
 assert.equal(changed.data.record.address,'Fictieve straat 1');
 const generated=await f.call(labels,'POST',{reference});
 assert.equal(generated.status,201,JSON.stringify(generated));
 assert.equal(generated.data.materials.length,3);
 assert.equal(new Set(generated.data.materials.map(item=>item.displayCode)).size,3);
 const [first,second]=generated.data.materials;
 const codePath=labels+'/'+first.id+'/code';
 assert.equal((await f.call(codePath,'PATCH',{previousCode:first.displayCode,code:second.displayCode})).status,409);
 const code='LSM-'+(first.displayCode==='LSM-FEDCBA'?'ABCDEF':'FEDCBA');
 const renamed=await f.call(codePath,'PATCH',{previousCode:first.displayCode,code});
 assert.equal(renamed.status,200,JSON.stringify(renamed));
 assert.equal(renamed.data.material.qrValue,first.qrValue);
 assert.equal((await f.call('/api/admin/operations/scan/'+first.displayCode)).status,404);
 assert.equal((await f.call('/api/admin/operations/scan/'+code)).data.material.id,first.id);
 const saved=await load();
 const replace=await f.call(path,'PATCH',{revision:saved.revision,serviceCode:'LS-NEW234'});
 assert.equal(replace.status,200,JSON.stringify(replace));
 const {teamStatusRecord}=await import('./src/team.js');
 assert.equal(await teamStatusRecord('LS-TEST23',f.env),null);
 assert.equal((await teamStatusRecord('LS-NEW234',f.env)).reference,reference);
 const [,untouched,removed]=generated.data.materials;
 const untouchedBefore=f.sql.prepare('SELECT * FROM materials WHERE id=?').get(untouched.id);
 const historyBefore=f.sql.prepare('SELECT * FROM maintenance_steps WHERE material_id=? ORDER BY step_order').all(untouched.id);
 const originalWorkflow=await f.call(labels+'/'+first.id+'/workflow');
 const inspection=originalWorkflow.data.workflow.steps.find(step=>step.code==='inspection');
 assert.ok(inspection);
 f.sql.prepare("UPDATE maintenance_steps SET status='completed',started_at='2026-11-11',completed_at='2026-11-11' WHERE id=?").run(inspection.id);
 const revised=await f.call(labels+'/'+first.id+'/set','PATCH',{package:'Brons'});
 assert.equal(revised.status,200,JSON.stringify(revised));
 assert.equal(revised.data.material.displayCode,code);
 assert.equal(revised.data.material.qrValue,first.qrValue);
 const steps=(await f.call(labels+'/'+first.id+'/workflow')).data.workflow.steps;
 assert.equal(steps.find(step=>step.code==='inspection').id,inspection.id);
 assert.ok(!steps.some(step=>step.code==='wax'));
 const deleted=await f.call(labels+'/'+removed.id+'/set','POST',{});
 assert.equal(deleted.status,200,JSON.stringify(deleted));
 assert.equal(deleted.data.record.amount,'2');
 assert.equal((await f.call('/api/admin/operations/scan/'+removed.displayCode)).status,404);
 const reloaded=await f.call(labels,'POST',{reference});
 assert.deepEqual(reloaded.data.materials.map(item=>item.id),[first.id,untouched.id]);
 assert.deepEqual(f.sql.prepare('SELECT * FROM materials WHERE id=?').get(untouched.id),untouchedBefore);
 assert.deepEqual(f.sql.prepare('SELECT * FROM maintenance_steps WHERE material_id=? ORDER BY step_order').all(untouched.id),historyBefore);
 const setCount=(targetCount,revision)=>f.call(labels+'/add-ski-pair','POST',{reference,revision,targetCount,package:'Goud'});
 const before=await load();
 const more=await setCount(3,before.revision);
 assert.equal(more.status,201,JSON.stringify(more));
 const expanded=(await f.call(labels+'?reference='+reference)).data.materials;
 assert.equal(expanded.filter(item=>item.kind==='Ski').length,3);
 assert.equal(expanded.find(item=>item.id===first.id).displayCode,code);
 assert.equal((await setCount(3,before.revision)).status,409);
 const less=await setCount(1,more.data.record.revision);
 assert.equal(less.status,201,JSON.stringify(less));
 assert.deepEqual((await f.call(labels+'?reference='+reference)).data.materials.map(item=>item.id),[first.id,untouched.id]);
 console.log('PASS editing request, adding a third set, unique set codes, replacement, stable QR and customer code rotation');
} finally { f.close(); }
